list = ["maça", "banana", "mamao"]

print(list)

print(list[0]) #mostra o primeiro da lista

print(len(list)) #mostra o tamanho da lista

list.append('larnaja') #inclui um intem na lista no final da lista 
print(list)

list.insert(0, 'caqui')# inclui um intem em uma posiçao especifica
print(list)

list.insert(3, "uva")
print(list)

list.remove("caqui")#remove um intem
print(list)

list.pop(2)#remove o ultimo iten da lista se nao ouver o numero 
print(list)

list.clear()#remove todos os itens
print(list)
